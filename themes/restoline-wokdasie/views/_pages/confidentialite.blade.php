    <h1>Politique de confidentialite</h1>

    <p>Cette page explique comment SRL JIN-ZHOU, exploitant La Grande Muraille de Chine, utilise les donnees personnelles collectees via ce site.</p>

    <h2>Responsable du traitement</h2>
    <p>SRL JIN-ZHOU, TVA BE 0812011942, Avenue Reine Astrid 98, 4900 Spa, Belgique. Telephone : <a href="tel:+3287220888">087 22 08 88</a>.</p>

    <h2>Donnees collectees</h2>
    <p>Pour les reservations, nous pouvons collecter le nom, le prenom, le telephone, l'email, la date, l'heure, le nombre de personnes et les demandes particulieres.</p>

    <h2>Finalites et bases legales</h2>
    <p>Les donnees de reservation sont utilisees pour gerer la demande de table, confirmer, modifier ou annuler la reservation. La base legale est l'execution de la demande du client.</p>

    <h2>Destinataires</h2>
    <p>Les donnees sont accessibles au restaurant et aux prestataires strictement necessaires au fonctionnement du site : hebergement, logiciel de reservation et envoi d'emails.</p>

    <h2>Duree de conservation</h2>
    <p>Les donnees de reservation sont conservees pendant la duree necessaire a la gestion du service, puis archivees selon les obligations comptables et administratives applicables.</p>

    <h2>Cookies</h2>
    <p>Le site utilise des cookies necessaires au fonctionnement technique du site, notamment pour la session et la securite. Aucun cookie publicitaire n'est necessaire pour utiliser le site.</p>

    <h2>Vos droits</h2>
    <p>Vous pouvez demander l'acces a vos donnees, leur correction, leur suppression ou la limitation du traitement.</p>
    <p>Vous pouvez egalement introduire une reclamation aupres de l'Autorite de protection des donnees en Belgique : <a href="https://www.autoriteprotectiondonnees.be" target="_blank" rel="noopener noreferrer">autoriteprotectiondonnees.be</a>.</p>
